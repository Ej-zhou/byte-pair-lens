"""Write the Unicode block list into docs/bytemap.js (between the UBLOCKS markers).

Usage:  python3 build_blocks.py [version]     (default 17.0.0; downloads Blocks.txt from unicode.org)
"""
import re, subprocess, sys
from pathlib import Path

version = sys.argv[1] if len(sys.argv) > 1 else '17.0.0'
txt = subprocess.run(['curl', '-sf', f'https://www.unicode.org/Public/{version}/ucd/Blocks.txt'],
                     capture_output=True, text=True, check=True).stdout
rows = []
for line in txt.splitlines():
    m = re.match(r'([0-9A-F]+)\.\.([0-9A-F]+); (.+)', line)
    if m:
        rows.append(f'[0x{m[1]},0x{m[2]},{m[3]!r}]'.replace("'", '"'))
js = Path(__file__).parent.parent / 'docs' / 'bytemap.js'
s = js.read_text()
body = f'  // Unicode {version} Blocks.txt, generated by scripts/build_blocks.py\n  const UBLOCKS = [\n    ' + ',\n    '.join(rows) + ',\n  ];\n'
s = re.sub(r'(  // >>> UBLOCKS\n).*?(  // <<< UBLOCKS\n)', lambda m: m[1] + body + m[2], s, flags=re.S)
js.write_text(s)
print(f'{len(rows)} blocks from Unicode {version}')
